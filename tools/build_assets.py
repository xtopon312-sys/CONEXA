"""Embed the complete offline page in flash; no web build dependencies."""
from __future__ import annotations

import argparse
import gzip
import hashlib
from html.parser import HTMLParser
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]


class ResourceAudit(HTMLParser):
    def handle_starttag(self, tag, attrs):
        for name, value in attrs:
            if not value:
                continue
            if name in ("src", "srcset", "href", "action") and re.search(
                r"(?:https?:)?//", value, re.I
            ):
                raise ValueError(f"Recurso externo proibido em {tag}.{name}")


def generate(source: Path, target: Path) -> dict:
    text = source.read_text(encoding="utf-8")
    # These delimited sections are generated from the small V1 source modules.
    # Runtime delivery remains one offline page; no script/style HTTP requests.
    for name in ("session_v1.js", "game_v1.js", "game_v1.css"):
        marker = name.upper().replace(".", "_")
        start, end = f"/* EMBED_{marker}_BEGIN */", f"/* EMBED_{marker}_END */"
        if start in text:
            module = (source.parent / name).read_text(encoding="utf-8")
            pattern = re.escape(start) + r"[\s\S]*?" + re.escape(end)
            text = re.sub(pattern, lambda _: start + "\n" + module + "\n" + end, text)
    raw = text.encode("utf-8")
    ResourceAudit().feed(text)
    if re.search(r"@import\s|url\(\s*[\"']?(?:https?:)?//", text, re.I):
        raise ValueError("CSS contém dependência externa")
    if re.search(r"(?:fetch|WebSocket|EventSource)\s*\(\s*[\"'](?:https?:|wss?:)?//", text):
        raise ValueError("JavaScript contém endpoint externo")
    if len(raw) > 262144:
        raise ValueError("HTML maior que o orçamento de 256 KiB de P0.1")
    payload = gzip.compress(raw, compresslevel=9, mtime=0)
    if len(payload) > 65536:
        raise ValueError("Página comprimida maior que o orçamento de 64 KiB")
    if source.read_bytes() != raw:
        source.write_bytes(raw)
    digest = hashlib.sha256(raw).hexdigest()
    lines = ["#pragma once", "/* Generated by tools/build_assets.py. */", "static const unsigned char CONEXA_WEB_GZIP[] = {"]
    for offset in range(0, len(payload), 16):
        lines.append("    " + ", ".join(f"0x{v:02x}" for v in payload[offset:offset+16]) + ",")
    lines += ["};", f"static const unsigned int CONEXA_WEB_GZIP_LEN = {len(payload)}u;", f'static const char CONEXA_WEB_ETAG[] = "\\\"{digest[:24]}\\\"";', ""]
    output = "\n".join(lines)
    target.parent.mkdir(parents=True, exist_ok=True)
    if not target.exists() or target.read_text(encoding="ascii") != output:
        temporary = target.with_suffix(target.suffix + ".tmp")
        temporary.write_text(output, encoding="ascii", newline="\n")
        temporary.replace(target)
    return {"html_bytes": len(raw), "gzip_bytes": len(payload), "sha256": digest}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT / "web" / "index.html")
    parser.add_argument("--target", type=Path, default=ROOT / "include" / "web_asset.h")
    args = parser.parse_args()
    try:
        info = generate(args.source, args.target)
    except (OSError, UnicodeError, ValueError) as exc:
        print(f"Não foi possível preparar a página: {exc}", file=sys.stderr)
        return 1
    print(f"Página offline: {info['html_bytes']} bytes; gzip: {info['gzip_bytes']} bytes.")
    print(f"SHA-256 HTML: {info['sha256']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
